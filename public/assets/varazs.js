    const crown = y < 16 && Math.abs(x - (W - 1) / 2) < 7;
    pts.push({ gx: x, gy: y, red: crown && rnd(i * 3) < .7, a: rnd(i) * Math.PI * 2, r: rnd(i + 7), s: rnd(i + 13), d: rnd(i + 19) });
