    if (t0 === null) t0 = now;
    const t = fixT !== null ? +fixT : (now - t0) / 1000;
    g.setTransform(dpr, 0, 0, dpr, 0, 0);
    const dark = document.documentElement.dataset.theme === 'dark';
    g.clearRect(0, 0, w, h);
